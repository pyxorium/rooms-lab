// copy-to-site.mjs: puts the Rooms lab page into the site (build step 5; modelled on daisy-tiles'
// copy-to-site.mjs). In C:\thunderbird-cafe\rooms-lab:
//
//   node scripts/copy-to-site.mjs C:\thunderbird-cafe\pyxorium.github.io
//
// It writes, in the site:
//   src/rooms-lab/<module>.js, room.css     the page modules from src\, copied (tested here: npm test and the
//                                           browser checks); edit them here, never in the site
//   src/rooms-lab/main.js, page-csp.js      the site's entry point and the page's security policy (site\)
//   src/rooms-lab/published.generated.js    the published house tile, pinned (address and record CID, from
//                                           published.json): the page loads exactly that version
//   src/pages/webtiles/rooms-lab/index.astro  the page (site\index.astro)
//
// Publish the house first (node scripts/publish.mjs): without published.json this script stops, so the
// live page is never pushed without its house. Run it again after publishing a new house (--again), or
// whenever the page modules change; then build, check and push the site.
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(fileURLToPath(new URL('.', import.meta.url)), '..');
export const MODULES = ['config.js', 'formats.js', 'room-link.js', 'mesh.js', 'levels.js', 'presenting.js', 'messages.js',
  'house-bridge.js', 'tile-records.js', 'hide-check.js', 'tile-strip.js', 'live.js', 'address.js', 'room-page.js'];
export const SITE_FILES = ['main.js', 'page-csp.js'];

const jsNote = (from) => `// COPY of rooms-lab/${from} (tested there). Edit it there, then run\n// node scripts/copy-to-site.mjs <site folder> in C:\\thunderbird-cafe\\rooms-lab to bring it here.\n\n`;
const cssNote = (from) => `/* COPY of rooms-lab/${from}. Edit it there, then run node scripts/copy-to-site.mjs <site folder>\n   in C:\\thunderbird-cafe\\rooms-lab to bring it here. */\n\n`;

/** The pinned house from published.json, or null. */
export function pinnedFrom(published) {
  const h = published && published.house;
  if (!h || typeof h.uri !== 'string' || typeof h.cid !== 'string') return null;
  return { account: published.account, house: { uri: h.uri, cid: h.cid } };
}

/** Every file to write, by its path in the site. */
export function siteFiles(published) {
  const pinned = pinnedFrom(published);
  if (!pinned) throw new Error('The house tile isn\u2019t published yet (no published.json here). Publish it first: node scripts/publish.mjs');
  const files = {};
  for (const m of MODULES) files[`src/rooms-lab/${m}`] = jsNote(`src/${m}`) + readFileSync(join(ROOT, 'src', m), 'utf8');
  files['src/rooms-lab/room.css'] = cssNote('src/room.css') + readFileSync(join(ROOT, 'src', 'room.css'), 'utf8');
  for (const m of SITE_FILES) files[`src/rooms-lab/${m}`] = jsNote(`site/${m}`) + readFileSync(join(ROOT, 'site', m), 'utf8');
  files['src/rooms-lab/published.generated.js'] = '// Generated by rooms-lab/scripts/copy-to-site.mjs from published.json: the published house tile, pinned\n' +
    '// (address and record CID). The page loads exactly this version; a changed record is refused (the room then\n' +
    "// falls back to \"the host approves each request\"). Don't edit; publish and run the script again.\n\n" +
    `export const PUBLISHED = ${JSON.stringify(pinned, null, 2)};\n`;
  const astro = readFileSync(join(ROOT, 'site', 'index.astro'), 'utf8');
  files['src/pages/webtiles/rooms-lab/index.astro'] = astro.replace(/^---\r?\n/, '---\n// COPY of rooms-lab/site/index.astro: edit it there, then run copy-to-site.mjs.\n');
  return { files, pinned };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const site = process.argv[2];
  if (!site || !existsSync(join(site, 'astro.config.mjs'))) {
    console.error('Usage: node scripts/copy-to-site.mjs C:\\thunderbird-cafe\\pyxorium.github.io  (the site folder)');
    process.exit(1);
  }
  const file = join(ROOT, 'published.json');
  let built;
  try {
    built = siteFiles(existsSync(file) ? JSON.parse(readFileSync(file, 'utf8')) : null);
  } catch (e) { console.error(e.message); process.exit(1); }
  for (const [rel, text] of Object.entries(built.files)) {
    const out = join(site, ...rel.split('/'));
    mkdirSync(join(out, '..'), { recursive: true });
    writeFileSync(out, text);
  }
  console.log(`Wrote ${Object.keys(built.files).length} files into ${site} (src\\rooms-lab\\ and the page), the house pinned to ${built.pinned.house.uri} (record ${built.pinned.house.cid}).`);
}
